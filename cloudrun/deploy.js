// Builds the app in Google Cloud and deploys it to Cloud Run as one service
// (web app + backend API in one container; see ../Dockerfile).
//
//   node cloudrun/deploy.js <gcp-project-id> [region] [--public]   build and deploy
//   node cloudrun/deploy.js --env-only                              only write the build settings
//
// A new service answers only to signed-in Google accounts that were given
// access to it (README.md in this folder says how to open it). With --public
// anyone who has the address can open it. Deploying again without --public
// leaves that setting as it is.
//
// Needs the gcloud CLI, signed in to an account that can administer the
// project. The hosted app talks to the Sepolia contracts in
// testnet/deployments.json and uses the dev wallet instead of MetaMask.
//
// The private keys from testnet/accounts.json (Sepolia deployer and the four
// role accounts) are stored in Secret Manager and given only to the backend
// API, which signs for the page; the page itself gets the addresses. With
// --public, anyone who has the address of the service can still ACT as those
// accounts through the app (that is what the dev wallet is for), limited to
// this deployment's contracts. Only ever deploy keys that hold nothing of value.
const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");
const { devWalletAccounts } = require("../testnet/app-env");

const root = path.join(__dirname, "..");
const NETWORK = "sepolia";
const SERVICE = "scefsta";
const DB_MOUNT = "/mnt/db";
const KEYS_SECRET = `${SERVICE}-dev-wallet-keys`;

function writeBuildSettings() {
  const file = path.join(root, "project_code", ".env.production.local");
  fs.writeFileSync(
    file,
    [
      "# Generated by cloudrun/deploy.js - do not commit",
      `NEXT_PUBLIC_NETWORK=${NETWORK}`,
      // the web server forwards /backend/* to the API (next.config.js)
      "NEXT_PUBLIC_API_URL=/backend",
      "NEXT_PUBLIC_DEV_WALLET=1",
      // addresses only: the keys go to Secret Manager (see main)
      `NEXT_PUBLIC_DEV_WALLET_ACCOUNTS=${devWalletAccounts(NETWORK).addresses}`,
    ].join("\n") + "\n"
  );
  console.log(`Wrote ${path.relative(root, file)}`);
}

// gcloud is a .cmd shim on Windows, so the command line goes through the shell
// (input: text for the command's standard input, used to hand over a secret
// without putting it on the command line)
function gcloud(args, { check = true, quiet = false, input } = {}) {
  const result = spawnSync(["gcloud", ...args].join(" "), {
    cwd: root,
    shell: true,
    encoding: "utf8",
    input,
    stdio: quiet || input !== undefined ? "pipe" : ["ignore", "inherit", "inherit"],
  });
  if (check && result.status !== 0) {
    if (quiet) process.stderr.write(result.stderr || "");
    throw new Error(`gcloud ${args.slice(0, 3).join(" ")} failed`);
  }
  return result;
}

function main() {
  writeBuildSettings();
  if (process.argv.includes("--env-only")) return;

  const isPublic = process.argv.includes("--public");
  const [project, region = "us-central1"] = process.argv
    .slice(2)
    .filter((argument) => !argument.startsWith("--"));
  if (!project) {
    console.error("Usage: node cloudrun/deploy.js <gcp-project-id> [region] [--public]");
    process.exit(1);
  }
  const bucket = `${project}-${SERVICE}-data`;
  const account = `${SERVICE}-run`;
  const accountEmail = `${account}@${project}.iam.gserviceaccount.com`;
  const inProject = `--project=${project}`;

  // 1. Bucket that keeps the database between container restarts
  if (gcloud(["storage", "buckets", "describe", `gs://${bucket}`, inProject], { check: false, quiet: true }).status !== 0) {
    gcloud([
      "storage", "buckets", "create", `gs://${bucket}`, inProject,
      `--location=${region}`, "--uniform-bucket-level-access", "--public-access-prevention",
    ]);
  }

  // 2. Identity the service runs as: it may use that bucket and nothing else
  if (gcloud(["iam", "service-accounts", "describe", accountEmail, inProject], { check: false, quiet: true }).status !== 0) {
    gcloud([
      "iam", "service-accounts", "create", account, inProject,
      '--display-name="SCeFSTA Cloud Run service"',
    ]);
  }
  // (a newly created identity can take a few seconds to become usable)
  for (let attempt = 1; ; attempt++) {
    const granted = gcloud([
      "storage", "buckets", "add-iam-policy-binding", `gs://${bucket}`, inProject,
      `--member=serviceAccount:${accountEmail}`, "--role=roles/storage.objectUser",
    ], { check: attempt === 6, quiet: true });
    if (granted.status === 0) break;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 5000);
  }

  // 3. The test accounts' private keys: kept in Secret Manager, readable only
  //    by the service's identity, and handed to the backend API as the
  //    DEV_WALLET_KEYS environment variable
  gcloud(["services", "enable", "secretmanager.googleapis.com", inProject], { quiet: true });
  const keys = devWalletAccounts(NETWORK).keys;
  const stored = gcloud(
    ["secrets", "versions", "access", "latest", `--secret=${KEYS_SECRET}`, inProject],
    { check: false, quiet: true }
  );
  if (stored.status !== 0) {
    const exists = gcloud(["secrets", "describe", KEYS_SECRET, inProject], { check: false, quiet: true }).status === 0;
    gcloud(
      exists
        ? ["secrets", "versions", "add", KEYS_SECRET, inProject, "--data-file=-"]
        : ["secrets", "create", KEYS_SECRET, inProject, "--replication-policy=automatic", "--data-file=-"],
      { input: keys }
    );
  } else if (stored.stdout !== keys) {
    gcloud(["secrets", "versions", "add", KEYS_SECRET, inProject, "--data-file=-"], { input: keys });
  }
  gcloud([
    "secrets", "add-iam-policy-binding", KEYS_SECRET, inProject,
    `--member=serviceAccount:${accountEmail}`, "--role=roles/secretmanager.secretAccessor",
  ], { quiet: true });

  // 4. First deployment for this contract: start from the local database, so
  //    the hosted app knows the same users and patients as the local one
  const { sqliteFile } = require(path.join(root, "backend-api", "db.js"));
  process.env.NETWORK = NETWORK;
  const localDb = sqliteFile();
  const hostedDb = `gs://${bucket}/${path.basename(localDb)}`;
  if (
    fs.existsSync(localDb) &&
    gcloud(["storage", "ls", hostedDb, inProject], { check: false, quiet: true }).status !== 0
  ) {
    gcloud(["storage", "cp", `"${localDb}"`, hostedDb, inProject]);
  }

  // 5. Build the container in Cloud Build and deploy it. One instance at most:
  //    the database is a single file.
  gcloud([
    "run", "deploy", SERVICE, inProject, `--region=${region}`,
    "--source=.", "--quiet",
    // without --public, who may open the service is left as it is (a new
    // service starts with sign-in required)
    ...(isPublic ? ["--allow-unauthenticated"] : []),
    `--service-account=${accountEmail}`,
    "--execution-environment=gen2",
    "--memory=1Gi", "--cpu=1", "--min-instances=0", "--max-instances=1",
    `--add-volume=name=db,type=cloud-storage,bucket=${bucket}`,
    `--add-volume-mount=volume=db,mount-path=${DB_MOUNT}`,
    `--set-env-vars=NETWORK=${NETWORK},SQLITE_BACKUP_DIR=${DB_MOUNT}`,
    `--set-secrets=DEV_WALLET_KEYS=${KEYS_SECRET}:latest`,
  ]);

  const url = gcloud(
    ["run", "services", "describe", SERVICE, inProject, `--region=${region}`, '--format="value(status.url)"'],
    { quiet: true }
  ).stdout.trim();
  console.log(`\nDeployed: ${url}`);
}

main();
