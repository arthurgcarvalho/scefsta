// Points the Next.js app and the backend API at one testnet deployment.
//
//   node app-env.js <sepolia|amoy|fuji> [--dev-wallet]
//
// Writes ../project_code/.env.local and ../backend-api/.env (both git-ignored).
// With --dev-wallet the app runs without MetaMask: the testnet keys from
// accounts.json are embedded in the local dev bundle and an account switcher
// appears in the page (see ../project_code/devWallet.js). Never use that flag
// with keys that hold real funds.
const fs = require("fs");
const path = require("path");
const { getNetwork } = require("./networks");
const { loadAccounts } = require("./accounts");

const API_PORT = 5001;

function main() {
  const net = getNetwork(process.argv[2]);
  const devWallet = process.argv.includes("--dev-wallet");
  const deployments = JSON.parse(
    fs.readFileSync(path.join(__dirname, "deployments.json"), "utf8")
  );
  if (!deployments[net.name]) {
    throw new Error(`Nothing deployed on ${net.name} yet; run "node deploy.js ${net.name}"`);
  }

  const appEnv = [
    "# Generated by testnet/app-env.js - do not commit",
    `NEXT_PUBLIC_NETWORK=${net.name}`,
    `NEXT_PUBLIC_API_URL=http://localhost:${API_PORT}`,
  ];
  if (devWallet) {
    const accounts = loadAccounts();
    const entries = [
      ["superAdmin", accounts.deployers[net.name]],
      ...Object.entries(accounts.roles),
    ].map(([label, account]) => `${label}:${account.privateKey}`);
    appEnv.push("NEXT_PUBLIC_DEV_WALLET=1");
    appEnv.push(`NEXT_PUBLIC_DEV_WALLET_ACCOUNTS=${entries.join(",")}`);
  }
  fs.writeFileSync(
    path.join(__dirname, "..", "project_code", ".env.local"),
    appEnv.join("\n") + "\n"
  );

  fs.writeFileSync(
    path.join(__dirname, "..", "backend-api", ".env"),
    [
      "# Generated by testnet/app-env.js - do not commit",
      `NETWORK=${net.name}`,
      `PORT=${API_PORT}`,
      "DB_DRIVER=sqlite",
    ].join("\n") + "\n"
  );

  console.log(
    `App configured for ${net.label}` +
      (devWallet ? " with the dev wallet (no MetaMask needed)" : " (MetaMask)")
  );
  console.log("Restart the backend and the Next.js dev server to apply.");
}

main();
